// Выход из системы.
//
// Firestore держит копию данных на диске браузера (IndexedDB) — ради быстрого
// входа, см. `src/firebase.js`. В этой копии лежат имена детей, телефоны
// родителей и все деньги, и она переживает выход: нажал «Выйти» — а данные
// остались лежать в браузере, читай кто хочет.
//
// Поэтому «Выйти» стирает копию. Именно «Выйти», а не закрытие вкладки: закрыл
// вкладку — значит отошёл, вернёшься и продолжишь; нажал «Выйти» — значит
// закончил, и на этом устройстве после тебя ничего оставаться не должно.
//
// Плата за это — следующий вход выкачает историю заново (около 3000 чтений из
// суточных 50 000). Поэтому именно «Выйти», а не каждое закрытие вкладки.

import { signOut } from 'firebase/auth'
import { terminate, clearIndexedDbPersistence } from 'firebase/firestore'
import { auth, db } from '../firebase'
import { stopAllLive } from './store'
import { withTimeout } from './withTimeout'

// Дольше этого выход ждать не должен: человек уже нажал кнопку.
const CLEAR_TIMEOUT_MS = 3000

export async function logout() {
  try {
    await signOut(auth)
  } catch (e) {
    // Сеть отвалилась — из системы всё равно выходим: держать человека внутри
    // из-за неудачного запроса нельзя, а токен всё равно уже недействителен.
    console.warn('[FinGam] Выход с ошибкой:', e?.code || e)
  }

  // Слушатели, пережившие выход, получат отказ по правам и засорят консоль.
  stopAllLive()

  try {
    // Стереть копию можно только у остановленного Firestore. После terminate()
    // экземпляр непригоден — поэтому ниже страница перезагружается.
    //
    // Под таймаутом обе операции: при открытой второй вкладке Firestore не
    // всегда отвечает отказом — он может просто замолчать, и тогда `await`
    // не вернётся никогда. Человек нажал бы «Выйти» и не увидел бы ничего.
    // Лучше выйти, не стерев копию, чем не выйти вовсе.
    await withTimeout(terminate(db), CLEAR_TIMEOUT_MS)
    await withTimeout(clearIndexedDbPersistence(db), CLEAR_TIMEOUT_MS)
  } catch (e) {
    // Не стёрли — открыта вторая вкладка или Firestore не ответил. Выход при
    // этом уже состоялся: не мешаем ему, но и не молчим — данные на диске
    // остались, и об этом должно быть видно в консоли.
    console.warn('[FinGam] Копия данных не стёрта:', e?.code || e)
  }

  // Чистый старт: Firestore остановлен, дальше приложению нужен новый экземпляр.
  window.location.replace(import.meta.env.BASE_URL)
}
