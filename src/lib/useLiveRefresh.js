// Перерисовать страницу, когда подписка Firestore принесла чужую правку.
//
// Данные слушаются живьём (`src/lib/store.js`), но страница держит их копию
// в `useState` — сама по себе она обновится только при следующем заходе
// на вкладку. Хук ставит мостик: пришёл снимок — перечитываем состояние
// страницы из уже загруженных данных. Обращений к базе это не стоит:
// строки лежат в подписке, читать нечего.

import { useEffect, useRef } from 'react'
import { watch } from './store'

export function useLiveRefresh(reload) {
  // `fetchData` пересоздаётся на каждый рендер. Держим её в ref, иначе
  // подписку пришлось бы снимать и вешать заново после каждой перерисовки.
  const latest = useRef(reload)
  useEffect(() => { latest.current = reload })
  useEffect(() => watch(() => latest.current()), [])
}
